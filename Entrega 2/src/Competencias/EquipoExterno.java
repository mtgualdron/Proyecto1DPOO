package Competencias;

public class EquipoExterno {
	private String nombre;
	private String club;
	
	public EquipoExterno(String nombre, String club) {
		super();
		this.nombre = nombre;
		this.club = club;
	}

	public String getNombre() {
		return nombre;
	}

	public String getClub() {
		return club;
	}
	
	
	

}
